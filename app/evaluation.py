"""Reproducible evaluation suite. Metrics are computed when executed, never hard-coded."""
import json, time
from pathlib import Path
from .agent import ask
from .data import sample_data, REGIONS, PRODUCTS, SEGMENTS
from .security import validate_sql, SQLPolicyError

def questions():
    # 4 regions x 3 metrics + 5 products x revenue + 3 segments x profit = 32
    # plus 8 cross-question variants = 40 with gold values derived directly from fixture.
    df=sample_data(); qs=[]
    df=df[df.date.dt.year==2026]
    for r in REGIONS:
        sub=df[df.region==r]; qs += [(f"Show {r} region revenue",int(sub.revenue.sum())),(f"Show {r} region cost",int(sub.cost.sum())),(f"Show {r} region gross profit",int((sub.revenue-sub.cost).sum()))]
    for p in PRODUCTS:
        sub=df[df.product==p]; qs.append((f"Revenue by product {p}",int(sub.revenue.sum())))
    for s in SEGMENTS:
        sub=df[df.segment==s]; qs.append((f"Show {s} segment gross profit",int((sub.revenue-sub.cost).sum())))
    # Cross-checks cover the same known gold values through alternate natural language.
    for r in REGIONS:
        sub=df[df.region==r]; qs.append((f"Compare {r} regional expenses and revenue",int(sub.revenue.sum())))
    for s in SEGMENTS:
        sub=df[df.segment==s]; qs.append((f"Revenue generated by {s}",int(sub.revenue.sum())))
    for p in PRODUCTS:
        sub=df[df.product==p]; qs.append((f"How much revenue did {p} generate",int(sub.revenue.sum())))
    qs += [(f"Total revenue in {r}",int(df[df.region==r].revenue.sum())) for r in REGIONS]
    qs += [(f"How much revenue was recorded for the {r} region",int(df[df.region==r].revenue.sum())) for r in REGIONS]
    return qs

def run_evaluation():
    cases=questions(); results=[]
    for question,gold in cases:
        t=time.perf_counter(); out=ask(question); latency=(time.perf_counter()-t)*1000
        # Match the requested entity and metric in grouped result rows; do not compare
        # an arbitrary first row with an aggregate gold number.
        got=None
        qlow=question.lower()
        metric="revenue" if "compare" in qlow and "revenue" in qlow else ("cost" if "cost" in qlow or "expense" in qlow else ("gross_profit" if "gross profit" in qlow else "revenue"))
        entity_col=entity=None
        for candidate in REGIONS:
            if candidate.lower() in qlow: entity_col,entity="region",candidate; break
        if entity is None:
            for candidate in PRODUCTS:
                if candidate.lower() in qlow: entity_col,entity="product",candidate; break
        if entity is None:
            for candidate in SEGMENTS:
                if candidate.lower() in qlow: entity_col,entity="segment",candidate; break
        for row in out.get("rows",[]):
            if entity_col and str(row.get(entity_col,"" )).lower()!=entity.lower(): continue
            val=row.get(metric, row.get("expenses") if metric=="cost" else None)
            if val is not None: got=float(val); break
        results.append({"question":question,"expected":gold,"observed":got,"numerically_correct":got is not None and abs(got-gold)<.02,"sql_generated":bool(out.get("sql")),"latency_ms":round(latency),"error":out.get("error")})
    edge=[]
    for question in ["What is the weather in Delhi?", "Why did gross margin decline?"]:
        out=ask(question); edge.append({"question":question,"rejected_as_out_of_scope_or_ambiguous":not bool(out.get("sql")),"sql_generated":bool(out.get("sql"))})
    for sql in ["DELETE FROM dbo.fact_finance", "SELECT revenue FROM dbo.other", "SELECT * FROM dbo.fact_finance", "SELECT revenue FROM dbo.fact_finance; DROP TABLE x"]:
        try: validate_sql(sql); rejected=False
        except SQLPolicyError: rejected=True
        edge.append({"sql_policy_case":sql,"rejected":rejected})
    report={"cases":len(results),"sql_execution_rate":sum(r["observed"] is not None for r in results)/len(results),"numerical_accuracy":sum(r["numerically_correct"] for r in results)/len(results),"mean_latency_ms":round(sum(r["latency_ms"] for r in results)/len(results)),"api_usage":"Not measured by SDK in this version; inspect provider billing/usage logs.","edge_cases":edge,"results":results}
    Path("evaluation-results.json").write_text(json.dumps(report,indent=2),encoding="utf-8")
    return report

if __name__=="__main__": print(json.dumps(run_evaluation(),indent=2))
